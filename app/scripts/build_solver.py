"""Bundle only the local numerical models into a worker; no runtime loading."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]
FILES = ['rc-analysis.js', 'ac-analysis.js', 'opamp-analysis.js', 'metrology.js', 'local-projects.js', 'semiconductors.js', 'free-model.js', 'parameter-study.js', 'rc-model.js', 'guided-trials.js', 'lab-model.js', 'study-context.js']
DISPATCH = '''
self.onmessage = event => {
  const {action, doc, params} = event.data;
  try {
    const options = {onProgress: fraction => self.postMessage({type:'progress', fraction})};
    const actions = {
      time: () => FreeModel.simulate(doc, options),
      bode: () => FreeModel.bode(doc),
      op: () => FreeModel.operatingPoint(doc),
      dc: () => FreeModel.dcSweep(doc, options),
      precision: () => FreeModel.convergence(doc),
      guidedTime: () => LabModel.simulate(params),
      guidedBode: () => LabModel.bode(params),
      guidedVtc: () => LabModel.vtc(params, options),
      context: () => StudyContext.build(event.data.text),
      parameterStudy: () => ParameterStudy.run(event.data.doc,event.data.study,options),
      metrologyData: () => Metrology.analyze(event.data.doc,event.data.study),
      opampData: () => {const result=OpampAnalysis.analyze(event.data.study.points, event.data.study);return event.data.doc?OpampAnalysis.compare(result,event.data.doc,FreeModel,event.data.study):result;}
    };
    if (!Object.hasOwn(actions, action)) throw new Error('Analisi non supportata.');
    self.postMessage({type:'progress', fraction:0});
    const result = actions[action]();
    self.postMessage({type:'result', result});
  } catch(error) { self.postMessage({type:'error', message:error.message}); }
};
'''
def build():
    source = '\n'.join((ROOT / name).read_text() for name in FILES) + DISPATCH
    temporary = ROOT / 'solver-source.js.tmp'
    temporary.write_text('/* Generated by scripts/build_solver.py. Local models only. */\nwindow.CircuitSolverSource=' + json.dumps(source, ensure_ascii=False) + ';\n')
    temporary.replace(ROOT / 'solver-source.js')
    return source
if __name__ == '__main__':
    print(f'Local worker: {len(build())} characters')
